  sql += `    b.name AS buildingName,\n`;
  sql += `    a.floorId,\n`;
  sql += `    f.name AS floorName,\n`;
  sql += `    a.roomId,\n`;
  sql += `    r.name AS roomName,\n`;
  sql += `    a.departmentId,\n`;
  sql += `    d.name AS departmentName,\n`;
  sql += `    a.vendorId,\n`;
  sql += `    v.name AS vendorName,\n`;
  sql += `    a.model,\n`;
  sql += `    a.brand,\n`;
  sql += `    a.brand AS manufacturer,\n`;
  sql += `    a.serialNumber,\n`;
  sql += `    a.serialNumber AS assetSerialNumber,\n`;
  sql += `    a.purchaseDate,\n`;
  sql += `    a.purchaseCost,\n`;
  sql += `    a.invoiceNumber,\n`;
  sql += `    a.assignedTo,\n`;
  sql += `    a.assignedTo AS assignedEmployee,\n`;
  sql += `    a.custodian,\n`;
  sql += `    a.warrantyExpiry,\n`;
  sql += `    a.amcExpiry,\n`;
  sql += `    a.barcode,\n`;
