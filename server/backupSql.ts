  sql += `    COALESCE(a.status, a.assetStatus, 'Active') AS status,\n`;
  sql += `    a.condition,\n`;
  sql += `    a.condition AS currentCondition,\n`;
  sql += `    a.categoryId,\n`;
  sql += `    COALESCE(a.category, c.name, a.categoryId) AS category,\n`;
  sql += `    COALESCE(c.name, a.category, a.categoryId) AS categoryName,\n`;
